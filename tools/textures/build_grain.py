"""
Writes mobile/notes/assets/textures/grain.png and web/notes/public/grain.png: the paper's tooth, a 256 px tile of
two-sided speckle (some grains darken, some lighten) on transparency. Both apps lay it over paper
at the theme's grain opacity.

Also writes the home-screen widgets' tile, android/.../res/drawable-<density>/wgen_grain_tile.png: the
same paper grain scaled to 200 dp per density, as the phone's Grain lays it; each widget drawable
sets its strength (tools/widgets/build_widget_resources.mjs).

and android/.../res/drawable-nodpi/wgen_ground_grain_tile.png and mobile/notes/assets/textures/ground-grain.png: the
web's film grain below, each of its pixels two by two, for the widgets' ground and the phone's (laid one
file pixel to one device pixel, src/ui/components/Grain.tsx).

Also writes web/notes/public/ground-grain.png: the ground's film grain, a 256 px tile where every pixel
darkens or lightens a little, so the ground's two tones read as one grainy gradient. Its strength
is in the file (it is laid at full opacity, as one more background layer over the ground's
gradient, in both themes), at its own size so no scaling blurs it.

Seeded, so a rerun gives the same files.

    python3 tools/textures/build_grain.py
"""
import os
import random
import struct
import zlib

SIZE = 256
SEED = 1947  # the year of Jazz
# The ground grain's strength: the spread of its pixels' alpha (out of 255).
GROUND_SIGMA = 13
# Read by the design tooling's raster provenance check.
PROVENANCE = (
    'Procedural texture, not generated by a model: tools/textures/build_grain.py '
    f'(seeded speckle, seed {SEED}), {SIZE}x{SIZE} RGBA tile of two-sided paper grain.'
)


def png(width, height, rows):
    def chunk(kind, data):
        body = kind + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xFFFFFFFF)

    raw = b''.join(b'\x00' + bytes(row) for row in rows)
    header = struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)
    text = chunk(b'tEXt', b'impeccable:prompt\x00' + PROVENANCE.encode('latin-1'))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', header) + text + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')


def grain():
    return png(SIZE, SIZE, grain_rows())


def grain_rows():
    rnd = random.Random(SEED)
    alpha = [[0] * SIZE for _ in range(SIZE)]
    light = [[False] * SIZE for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            roll = rnd.random()
            if roll < 0.16:
                alpha[y][x] = rnd.randint(14, 46)
            elif roll < 0.27:
                alpha[y][x] = rnd.randint(18, 52)
                light[y][x] = True
    # A few fibres: short soft clusters, wrapped so the tile repeats without a seam.
    for _ in range(420):
        cx, cy = rnd.randrange(SIZE), rnd.randrange(SIZE)
        bright = rnd.random() < 0.45
        for _ in range(rnd.randint(2, 5)):
            x, y = (cx + rnd.randint(-1, 1)) % SIZE, (cy + rnd.randint(-1, 1)) % SIZE
            alpha[y][x] = max(alpha[y][x], rnd.randint(30, 64))
            light[y][x] = bright
    rows = []
    for y in range(SIZE):
        row = []
        for x in range(SIZE):
            tone = 255 if light[y][x] else 0
            row += [tone, tone, tone, alpha[y][x]]
        rows.append(row)
    return rows


# The phone lays the tile at 200 dp (src/ui/components/Grain.tsx); a launcher tiles a bitmap at its own size.
WIDGET_TILE_DP = 200
WIDGET_DENSITIES = {'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0}


def scaled(rows, size):
    """The tile resampled to `size` px, bilinear on premultiplied colour (as an image view scales it), wrapping at its edges."""
    def at(x, y):
        px = rows[y % SIZE][(x % SIZE) * 4:(x % SIZE) * 4 + 4]
        return px[0] * px[3], px[3]
    out = []
    step = SIZE / size
    for j in range(size):
        sy = (j + 0.5) * step - 0.5
        y0 = int(sy // 1)
        fy = sy - y0
        row = []
        for i in range(size):
            sx = (i + 0.5) * step - 0.5
            x0 = int(sx // 1)
            fx = sx - x0
            c00, a00 = at(x0, y0)
            c10, a10 = at(x0 + 1, y0)
            c01, a01 = at(x0, y0 + 1)
            c11, a11 = at(x0 + 1, y0 + 1)
            a = (a00 * (1 - fx) + a10 * fx) * (1 - fy) + (a01 * (1 - fx) + a11 * fx) * fy
            c = (c00 * (1 - fx) + c10 * fx) * (1 - fy) + (c01 * (1 - fx) + c11 * fx) * fy
            tone = int(round(c / a)) if a > 0 else 0
            row += [tone, tone, tone, int(round(a))]
        out.append(row)
    return out


def widget_tiles():
    rows = grain_rows()
    for bucket, scale in WIDGET_DENSITIES.items():
        size = round(WIDGET_TILE_DP * scale)
        write((f'mobile/notes/android/app/src/main/res/drawable-{bucket}/wgen_grain_tile.png',), png(size, size, scaled(rows, size)))


def ground_grain():
    return png(SIZE, SIZE, ground_grain_rows())


def widget_ground_tile():
    """The film grain, each pixel two by two (nearest), so it reads on a phone as it does on a monitor."""
    rows = ground_grain_rows()
    out = []
    for row in rows:
        doubled = []
        for x in range(SIZE):
            doubled += row[x * 4:x * 4 + 4] * 2
        out += [doubled, list(doubled)]
    write(('mobile/notes/android/app/src/main/res/drawable-nodpi/wgen_ground_grain_tile.png', 'mobile/notes/assets/textures/ground-grain.png'), png(SIZE * 2, SIZE * 2, out))


def ground_grain_rows():
    rnd = random.Random(SEED + 1)
    rows = []
    for _ in range(SIZE):
        row = []
        for _ in range(SIZE):
            # Every pixel moves: a soft bell of strengths, as many lighter as darker.
            strength = min(255, int(abs(rnd.gauss(0, GROUND_SIGMA))))
            tone = 255 if rnd.random() < 0.5 else 0
            row += [tone, tone, tone, strength]
        rows.append(row)
    return rows


def write(paths, data):
    for path in paths:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as out:
            out.write(data)
        print(path, len(data))


if __name__ == '__main__':
    write(('mobile/notes/assets/textures/grain.png', 'web/notes/public/grain.png'), grain())
    write(('web/notes/public/ground-grain.png',), ground_grain())
    widget_tiles()
    widget_ground_tile()
