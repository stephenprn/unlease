/** The top-left corner of a box with `radius` (and of its line drawn `inset` in), in a `reach` square: reach, fill path, edge path. */
function corner(radius) {
  // A box large enough that no cap or budget bends the corner.
  const big = 1000;
  const piece = (outline, from) => {
    const s = outline.segments;
    const n = s.length;
    const [x0, y0] = [s[n - 4][4], s[n - 4][5]];
    const curves = s.slice(n - 3).map(g => `C${g.map(round).join(',')}`).join(' ');
    return { from: [x0, y0], curves, to: [s[n - 1][4], s[n - 1][5]], start: from };
  };
  const outer = piece(squircleSegments(big, big, [radius, radius, radius, radius]));
  const reach = outer.to[0];
  const fill = `M0,${round(reach)} L${round(outer.from[0])},${round(outer.from[1])} ${outer.curves} L${round(reach)},${round(reach)} Z`;
  // The 1dp line runs half a dp in, concentric, out to the square's sides so the bands meet it.
  const inner = piece(squircleSegments(big, big, [radius, radius, radius, radius], 0.5));
  const edge = `M0.5,${round(reach)} L${round(inner.from[0])},${round(inner.from[1])} ${inner.curves} L${round(reach)},0.5`;
  return { reach, fill, edge };
}

/** A path drawn in the top-left square, moved to another corner by mirroring. */
const CORNERS = { tl: [false, false], tr: [true, false], bl: [false, true], br: [true, true] };
const GRAVITY = { tl: 'top|left', tr: 'top|right', bl: 'bottom|left', br: 'bottom|right' };
const mirrored = (reach, [flipX, flipY]) =>
  flipX || flipY ? ` android:scaleX="${flipX ? -1 : 1}" android:scaleY="${flipY ? -1 : 1}" android:pivotX="${round(reach / 2)}" android:pivotY="${round(reach / 2)}"` : '';

function cornerVector(name, reach, path, paint, flip) {
  drawable(
    name,
    `<vector ${ANDROID} android:width="${dp(reach)}" android:height="${dp(reach)}" android:viewportWidth="${round(reach)}" android:viewportHeight="${round(reach)}">\n` +
      `  <group${mirrored(reach, flip)}>\n    <path android:pathData="${path}" ${paint}/>\n  </group>\n</vector>\n`,
  );
}

const solid = color => `<shape android:shape="rectangle"><solid android:color="@color/${PREFIX}${color}"/></shape>`;

/** A filled sheet: corners, then a top band, the middle and a bottom band, none overlapping (a see-through fill stays even). */
function sheetFill(name, radius, color) {
  const { reach, fill } = corner(radius);
  const items = Object.entries(CORNERS).map(([key, flip]) => {
    cornerVector(`${name}_${key}`, reach, fill, `android:fillColor="@color/${PREFIX}${color}"`, flip);
    return `  <item android:gravity="${GRAVITY[key]}" android:width="${dp(reach)}" android:height="${dp(reach)}" android:drawable="@drawable/${PREFIX}${name}_${key}"/>`;
  });
  items.push(
    `  <item android:gravity="top" android:height="${dp(reach)}" android:left="${dp(reach)}" android:right="${dp(reach)}">${solid(color)}</item>`,
    `  <item android:top="${dp(reach)}" android:bottom="${dp(reach)}">${solid(color)}</item>`,
    `  <item android:gravity="bottom" android:height="${dp(reach)}" android:left="${dp(reach)}" android:right="${dp(reach)}">${solid(color)}</item>`,
  );
  drawable(name, `<layer-list ${ANDROID}>\n${items.join('\n')}\n</layer-list>\n`);
  return name;
}

/** A sheet's 1dp edge, drawn inside its outline: four corner lines and four straight bands. */
function sheetEdge(name, radius, color) {
  const { reach, edge } = corner(radius);
  const items = Object.entries(CORNERS).map(([key, flip]) => {
    cornerVector(
      `${name}_${key}`,
      reach,
      edge,
      `android:fillColor="#00000000" android:strokeColor="@color/${PREFIX}${color}" android:strokeWidth="1"`,
      flip,
    );
    return `  <item android:gravity="${GRAVITY[key]}" android:width="${dp(reach)}" android:height="${dp(reach)}" android:drawable="@drawable/${PREFIX}${name}_${key}"/>`;
  });
  items.push(
    `  <item android:gravity="top" android:height="1dp" android:left="${dp(reach)}" android:right="${dp(reach)}">${solid(color)}</item>`,
    `  <item android:gravity="bottom" android:height="1dp" android:left="${dp(reach)}" android:right="${dp(reach)}">${solid(color)}</item>`,
    `  <item android:gravity="left" android:width="1dp" android:top="${dp(reach)}" android:bottom="${dp(reach)}">${solid(color)}</item>`,
    `  <item android:gravity="right" android:width="1dp" android:top="${dp(reach)}" android:bottom="${dp(reach)}">${solid(color)}</item>`,
  );
  drawable(name, `<layer-list ${ANDROID}>\n${items.join('\n')}\n</layer-list>\n`);
  return name;
}

