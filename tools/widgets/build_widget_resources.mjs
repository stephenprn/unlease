/** `#RRGGBB` or `rgba(r, g, b, a)` as Android's `#AARRGGBB`. */
function androidColor(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) return `#FF${hex[1].toUpperCase()}`;
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (!rgba) throw new Error(`colour ${value}`);
  const byte = n => Number(n).toString(16).padStart(2, '0').toUpperCase();
  return `#${byte(Math.round(Number(rgba[4]) * 255))}${byte(rgba[1])}${byte(rgba[2])}${byte(rgba[3])}`;
}

/** The ink at `alpha`, as the app's press tint lays it inside a control. */
const inkAt = (mode, alpha) => {
  const [r, g, b] = [1, 3, 5].map(i => parseInt(ROLES[mode].ink.slice(i, i + 2), 16));
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
};

