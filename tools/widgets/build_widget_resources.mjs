// Onde glyphs: one even line with round ends, in the ink they are shown in.

/** `size`: its box in dp, for a glyph drawn at its own size (beside text); an image view sizes the others. */
function glyph(name, ink, size = 24) {
  const form = GLYPHS[name]?.line;
  if (!form) throw new Error(`no glyph ${name}`);
  const color = `@color/${PREFIX}${ink}`;
  const paths = [
    form.stroke
      ? `  <path android:pathData="${form.stroke}" android:fillColor="#00000000" android:strokeColor="${color}" android:strokeWidth="${GLYPH_STROKE}" android:strokeLineCap="round" android:strokeLineJoin="round"/>\n`
      : '',
    form.fill ? `  <path android:pathData="${form.fill}" android:fillColor="${color}" android:fillType="evenOdd"/>\n` : '',
  ].join('');
  const key = `g_${name.replace(/[A-Z]/g, c => `_${c.toLowerCase()}`)}${ink === 'ink' ? '' : `_${ink}`}`;
  drawable(key, `<vector ${ANDROID} android:width="${size}dp" android:height="${size}dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths}</vector>\n`);
  return key;
}

