/** The top-left corner's curve as points from (0, reach) to (reach, 0), for where a grain piece may start. */
function curveOf(radius) {
  const outline = squircleSegments(1000, 1000, [radius, radius, radius, radius]);
  const s = outline.segments;
  const n = s.length;
  let from = [s[n - 4][4], s[n - 4][5]];
  const points = [from];
  for (const g of s.slice(n - 3)) {
    for (let i = 1; i <= 64; i += 1) {
      const t = i / 64;
      const u = 1 - t;
      points.push([
        u * u * u * from[0] + 3 * u * u * t * g[0] + 3 * u * t * t * g[2] + t * t * t * g[4],
        u * u * u * from[1] + 3 * u * u * t * g[1] + 3 * u * t * t * g[3] + t * t * t * g[5],
      ]);
    }
    from = [g[4], g[5]];
  }
  return points;
}

/**
 * The grain over a sheet of `radius`, as layer-list items: the inside (inset to the arc's middle),
 * the straight edges between the corners, and three steps along each corner's curve, none overlapping
 * (a see-through tile laid twice would show), none past the outline.
 */
function grainItems(radius, grain) {
  const points = curveOf(radius);
  const reach = points[points.length - 1][0];
  // The curve's x where it is `y` from the top edge (it falls from (0, reach) to (reach, 0)).
  const xAt = y => {
    for (let i = 1; i < points.length; i += 1) {
      const [x0, y0] = points[i - 1];
      const [x1, y1] = points[i];
      if (y <= y0 && y >= y1) return y0 === y1 ? x1 : x0 + ((y0 - y) / (y0 - y1)) * (x1 - x0);
    }
    return reach;
  };
  // The arc's middle lies radius (1 - 1/sqrt 2) in from both edges: inside that square, everything is the sheet.
  const inset = Math.ceil(radius * (1 - Math.SQRT1_2) + 0.5);
  const at = `android:drawable="@drawable/${PREFIX}${grain}"`;
  // A tile's own size (200 dp) would become the sheet's least size: every stretching piece says 1 dp, and fills.
  const items = [
    `<item android:gravity="fill" android:width="1dp" android:height="1dp" android:left="${dp(inset)}" android:top="${dp(inset)}" android:right="${dp(inset)}" android:bottom="${dp(inset)}" ${at}/>`,
    `<item android:gravity="top|fill_horizontal" android:width="1dp" android:height="${dp(inset)}" android:left="${dp(reach)}" android:right="${dp(reach)}" ${at}/>`,
    `<item android:gravity="bottom|fill_horizontal" android:width="1dp" android:height="${dp(inset)}" android:left="${dp(reach)}" android:right="${dp(reach)}" ${at}/>`,
    `<item android:gravity="left|fill_vertical" android:width="${dp(inset)}" android:height="1dp" android:top="${dp(reach)}" android:bottom="${dp(reach)}" ${at}/>`,
    `<item android:gravity="right|fill_vertical" android:width="${dp(inset)}" android:height="1dp" android:top="${dp(reach)}" android:bottom="${dp(reach)}" ${at}/>`,
  ];
  const levels = [0.25, 0.5, 0.75, 1].map(f => f * inset);
  for (let k = 0; k < 3; k += 1) {
    const [y0, y1] = [levels[k], levels[k + 1]];
    // Never inside the inset square, which the inside piece already covers.
    const x0 = Math.max(xAt(y0), inset);
    if (x0 >= reach) continue;
    const along = dp(reach - x0);
    const across = dp(y1 - y0);
    // Along the top and bottom edges, then the same steps turned along the sides.
    items.push(
      `<item android:gravity="top|left" android:left="${dp(x0)}" android:top="${dp(y0)}" android:width="${along}" android:height="${across}" ${at}/>`,
      `<item android:gravity="top|right" android:right="${dp(x0)}" android:top="${dp(y0)}" android:width="${along}" android:height="${across}" ${at}/>`,
      `<item android:gravity="bottom|left" android:left="${dp(x0)}" android:bottom="${dp(y0)}" android:width="${along}" android:height="${across}" ${at}/>`,
      `<item android:gravity="bottom|right" android:right="${dp(x0)}" android:bottom="${dp(y0)}" android:width="${along}" android:height="${across}" ${at}/>`,
      `<item android:gravity="top|left" android:top="${dp(x0)}" android:left="${dp(y0)}" android:height="${along}" android:width="${across}" ${at}/>`,
      `<item android:gravity="bottom|left" android:bottom="${dp(x0)}" android:left="${dp(y0)}" android:height="${along}" android:width="${across}" ${at}/>`,
      `<item android:gravity="top|right" android:top="${dp(x0)}" android:right="${dp(y0)}" android:height="${along}" android:width="${across}" ${at}/>`,
      `<item android:gravity="bottom|right" android:bottom="${dp(x0)}" android:right="${dp(y0)}" android:height="${along}" android:width="${across}" ${at}/>`,
    );
  }
  return items.map(item => `  ${item}`);
}

/** The ground as a sheet: its top tone above, its foot tone below, the two running into each other down the middle; its grain over it. */
function groundSheet(name, radius) {
  const { reach, fill } = corner(radius);
  const tone = { tl: 'ground_top', tr: 'ground_top', bl: 'ground_bottom', br: 'ground_bottom' };
  const items = Object.entries(CORNERS).map(([key, flip]) => {
    cornerVector(`${name}_${key}`, reach, fill, `android:fillColor="@color/${PREFIX}${tone[key]}"`, flip);
    return `  <item android:gravity="${GRAVITY[key]}" android:width="${dp(reach)}" android:height="${dp(reach)}" android:drawable="@drawable/${PREFIX}${name}_${key}"/>`;
  });
  items.push(
    `  <item android:gravity="top" android:height="${dp(reach)}" android:left="${dp(reach)}" android:right="${dp(reach)}">${solid('ground_top')}</item>`,
    `  <item android:top="${dp(reach)}" android:bottom="${dp(reach)}"><shape android:shape="rectangle"><gradient android:angle="270" android:startColor="@color/${PREFIX}ground_top" android:endColor="@color/${PREFIX}ground_bottom"/></shape></item>`,
    `  <item android:gravity="bottom" android:height="${dp(reach)}" android:left="${dp(reach)}" android:right="${dp(reach)}">${solid('ground_bottom')}</item>`,
    ...grainItems(radius, 'grain_ground'),
  );
  drawable(name, `<layer-list ${ANDROID}>\n${items.join('\n')}\n</layer-list>\n`);
}

/** A flat sheet in `color` under the grain at `grain`'s strength. */
