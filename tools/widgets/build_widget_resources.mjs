/**
 * Generates Carnet's home-screen widgets' resources from packages/design, so the widgets cannot drift
 * from the app: their colours (palette.ts, backgrounds.ts), their sheets with the continuous corner
 * (shapes.ts), the pebble (pebbles.ts), the collection emblems and the label tag (emblems.ts), the
 * Onde glyphs they show (glyphs.ts), and WidgetRes.kt, the keys their data names.
 *
 * A widget is drawn by the launcher from XML, which has no path clip: each sheet is a layer list of
 * its four corners (small vectors cut from `squircleSegments`) and three bands between them, so it
 * keeps the app's corner at any size. The ground's two tones run down the middle band; the grain
 * (the app's tile, tools/textures/build_grain.py) is laid in pieces that step along each corner's
 * curve, since a tile cannot be clipped. Run from the repository root: node tools/widgets/build_widget_resources.mjs
 */
