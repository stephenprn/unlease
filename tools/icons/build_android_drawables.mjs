/**
 * Generates the Android vector drawables (launcher, notification, the widgets' mark) from
 * packages/design/src/mark.ts and palette.ts (the widgets' own resources: tools/widgets/build_widget_resources.mjs). Run from the repository root.
 * Each app's own, in its Android project: Carnet's launcher, its reminders' notification icon and
 * its widgets' mark (the card and its leaf); Pages' launcher (the sheet and its writing); Contacts'
 * launcher, its birthdays' status bar icon and its widgets' mark (the card and its person); Agenda's
 * launcher, its reminders' status bar icon and its widgets' mark (the page and its days).
 *
 * Each app's launcher comes in every palette's primary too (`PALETTES`, design/appearance.ts): the
 * pebble as `markColors` paints it, the card and the themed silhouette the same. Android cannot paint
 * a launcher icon, so each is the icon of a launcher entry of its own (an `<activity-alias>` of
 * MainActivity, written here between the marks in each app's manifest), and the app turns on the one
 * for the person's primary (mobile/shared/src/app/launcherIcon.ts). Carnet's palette is the icon as it
 * always was (`@mipmap/ic_launcher`). Every entry names the app's static shortcuts (`res/xml/shortcuts.xml`):
 * the launcher shows those of the entry that is on.
 *
 * The static shortcuts' icons too (a long press on the app's icon): an Onde glyph on the mark's tile,
 * as Material draws a shortcut (a 24 glyph in a 44 circle), static as the widgets are (they never follow
 * the palette); and Carnet's Quick Settings tile, the glyph alone in white (Android tints it).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { register } from 'node:module';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// The design modules are TypeScript with extensionless imports and the packages' names (`@unlease/core/…`):
// Node strips the types, this hook finds the files (as tools/widgets/build_widget_resources.mjs does).
const PACKAGES = pathToFileURL(resolve('packages')).href;
register(
  'data:text/javascript,' +
    encodeURIComponent(`
      export async function resolve(specifier, context, next) {
        const shared = /^@unlease\\/(core|design)\\/(.+)$/.exec(specifier);
        if (shared) specifier = ${JSON.stringify(PACKAGES)} + '/' + shared[1] + '/src/' + shared[2];
        if ((shared || specifier.startsWith('.')) && !specifier.endsWith('.ts') && !specifier.endsWith('.json')) {
          // A folder (../i18n) is its index.
          try {
            return await next(specifier + '.ts', context);
          } catch {
            return next(specifier + '/index.ts', context);
          }
        }
        return next(specifier, context);
      }`),
);
const { PALETTES, PALETTE_COLORS, markColors } = await import(pathToFileURL(resolve('packages/design/src/appearance.ts')).href);
const { GLYPHS, GLYPH_STROKE } = await import(pathToFileURL(resolve('packages/design/src/glyphs.ts')).href);

const CARNET_RES = resolve('mobile/notes/android/app/src/main/res');
const PAGES_RES = resolve('mobile/pages/android/app/src/main/res');
const CONTACTS_RES = resolve('mobile/contacts/android/app/src/main/res');
const CALENDAR_RES = resolve('mobile/calendar/android/app/src/main/res');

const markSource = readFileSync('packages/design/src/mark.ts', 'utf8');
const markPath = name => new RegExp(`${name} =\\s*'([^']+)'`).exec(markSource)[1];
const markBox = name => Object.fromEntries([...new RegExp(`${name} = \\{([^}]*)\\}`).exec(markSource)[1].matchAll(/(\w+): (-?[\d.]+)/g)].map(([, key, value]) => [key, Number(value)]));
const PEBBLE = markPath('MARK_PEBBLE');
const CARD = markPath('MARK_CARD');
const PAGE = markPath('MARK_PAGE');
const CONTACT = markPath('MARK_CONTACT');
const CALENDAR = markPath('MARK_CALENDAR');
const BOUNDS = markBox('MARK_BOUNDS');

const paletteSource = readFileSync('packages/design/src/palette.ts', 'utf8');
const role = (mode, name) => {
  const block = new RegExp(`  ${mode}: \\{([\\s\\S]*?)\\n  \\}`).exec(paletteSource)[1];
  return new RegExp(`\\b${name}: '([^']+)'`).exec(block)[1];
};
const markBlock = /MARK_COLORS = \{([\s\S]*?)\}/.exec(paletteSource)[1];
const markColor = name => {
  const value = new RegExp(`${name}: ([^,\\n]+)`).exec(markBlock)[1].trim();
  const reference = /^ROLES\.(\w+)\.(\w+)$/.exec(value);
  return reference ? role(reference[1], reference[2]) : value.replace(/'/g, '');
};
const TILE = markColor('tile');
const CARD_INK = markColor('card');
const header = '<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/icons/build_android_drawables.mjs: do not edit. -->\n';
const writeIn = res => (file, body) => {
  const path = resolve(res, file);
  mkdirSync(resolve(path, '..'), { recursive: true });
  writeFileSync(path, header + body);
  console.log(path.slice(resolve('.').length + 1));
};

/** A mark's shape (what it holds cut out) on the mark's 100 grid, scaled by `scale` and moved by (tx, ty); `fill` for a one-colour silhouette. */
const shapeOf = path => (scale, tx, ty, indent, fill = CARD_INK) =>
  `${indent}<group android:translateX="${tx}" android:translateY="${ty}" android:scaleX="${scale}" android:scaleY="${scale}">\n` +
  `${indent}  <path android:pathData="${path}" android:fillColor="${fill}" android:fillType="evenOdd"/>\n` +
  `${indent}</group>\n`;
const card = shapeOf(CARD);
const page = shapeOf(PAGE);
const contact = shapeOf(CONTACT);
const calendar = shapeOf(CALENDAR);
const vector = (dp, viewport, body) =>
  `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${dp}dp" android:height="${dp}dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">\n${body}</vector>\n`;

/** An app's launcher: the adaptive icon's foreground and themed silhouette, and Android 7's own. */
function launcher(write, shape) {
  // Adaptive icon: 108dp canvas on the matcha ground (ic_launcher_background); the launcher shows the middle 72, the mark's 100 grid.
  write('drawable/ic_launcher_foreground.xml', vector(108, 108, shape(0.72, 18, 18, '  ')));
  // Themed icon: one colour, the same placement; what it holds is a hole either way.
  write('drawable/ic_launcher_monochrome.xml', vector(108, 108, shape(0.72, 18, 18, '  ', '#FFFFFFFF')));
  // Android 7 has no adaptive icons: the shape on a matcha pebble.
  write('drawable/ic_launcher_legacy.xml', vector(48, 100, `  <path android:pathData="${PEBBLE}" android:fillColor="${TILE}"/>\n${shape(1, 0, 0, '  ')}`));
}

/** A palette's launcher entry, as its manifest names it: `.LauncherSarcelle`. */
const entryName = key => `.Launcher${key[0].toUpperCase()}${key.slice(1)}`;
const ENTRIES_BEGIN = '<!-- GENERATED by tools/icons/build_android_drawables.mjs, do not edit: the launcher entries -->';
const ENTRIES_END = '<!-- GENERATED: end of the launcher entries -->';

/**
 * An app's launcher in every other palette (its foreground and themed silhouette are the default's:
 * only the pebble changes), and its launcher entries, one per palette, written into its manifest.
 */
function launcherPalettes(res, write, shape) {
  const others = PALETTES.filter(key => key !== 'carnet');
  const tile = key => markColors(PALETTE_COLORS[key].primary).tile;
  write(
    'values/ic_launcher_palettes.xml',
    `<resources>\n${others.map(key => `    <color name="ic_launcher_background_${key}">${tile(key)}</color>\n`).join('')}</resources>\n`,
  );
  for (const key of others) {
    write(
      `mipmap-anydpi-v26/ic_launcher_${key}.xml`,
      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n' +
        `    <background android:drawable="@color/ic_launcher_background_${key}" />\n` +
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n' +
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n' +
        '</adaptive-icon>\n',
    );
    write(`mipmap-anydpi/ic_launcher_${key}.xml`, `<inset xmlns:android="http://schemas.android.com/apk/res/android" android:drawable="@drawable/ic_launcher_legacy_${key}" android:inset="0dp" />\n`);
    write(`drawable/ic_launcher_legacy_${key}.xml`, vector(48, 100, `  <path android:pathData="${PEBBLE}" android:fillColor="${tile(key)}"/>\n${shape(1, 0, 0, '  ')}`));
  }

  // The entries, right after MainActivity (an alias follows its target). Carnet's is on as installed; the
  // app turns on another (LauncherIconModule) by the palette its meta-data names. Never rename or remove
  // one: a phone that turned it on would lose the app from its launcher.
  const indent = '      ';
  const entries = PALETTES.map(key => {
    const icon = key === 'carnet' ? ['@mipmap/ic_launcher', '@mipmap/ic_launcher_round'] : [`@mipmap/ic_launcher_${key}`, `@mipmap/ic_launcher_${key}`];
    return [
      '<activity-alias',
      `  android:name="${entryName(key)}"`,
      '  android:targetActivity=".MainActivity"',
      '  android:label="@string/app_name"',
      `  android:icon="${icon[0]}"`,
      `  android:roundIcon="${icon[1]}"`,
      `  android:enabled="${key === 'carnet'}"`,
      '  android:exported="true">',
      '  <intent-filter>',
      '    <action android:name="android.intent.action.MAIN" />',
      '    <category android:name="android.intent.category.LAUNCHER" />',
      '  </intent-filter>',
      `  <meta-data android:name="com.stephenprn.unlease.launcher.palette" android:value="${key}" />`,
      '  <meta-data android:name="android.app.shortcuts" android:resource="@xml/shortcuts" />',
      '</activity-alias>',
    ]
      .map(line => indent + line)
      .join('\n');
  });
  const manifestPath = resolve(res, '../AndroidManifest.xml');
  const manifest = readFileSync(manifestPath, 'utf8');
  const begin = manifest.indexOf(ENTRIES_BEGIN);
  const end = manifest.indexOf(ENTRIES_END);
  if (begin < 0 || end < begin) throw new Error(`${manifestPath}: the launcher entries' marks are missing (${ENTRIES_BEGIN} … ${ENTRIES_END}), right after MainActivity.`);
  const next = `${manifest.slice(0, begin)}${ENTRIES_BEGIN}\n${entries.join('\n')}\n${indent}${manifest.slice(end)}`;
  if (next !== manifest) {
    writeFileSync(manifestPath, next);
    console.log(manifestPath.slice(resolve('.').length + 1));
  }
}

/** An Onde glyph (24 grid) as vector paths, scaled by `scale` and moved by (tx, ty), in `ink`. */
function glyphPaths(name, scale, tx, ty, ink, indent = '  ') {
  const form = GLYPHS[name]?.line;
  if (!form) throw new Error(`no glyph ${name}`);
  return (
    `${indent}<group android:translateX="${tx}" android:translateY="${ty}" android:scaleX="${scale}" android:scaleY="${scale}">\n` +
    (form.stroke
      ? `${indent}  <path android:pathData="${form.stroke}" android:fillColor="#00000000" android:strokeColor="${ink}" android:strokeWidth="${GLYPH_STROKE}" android:strokeLineCap="round" android:strokeLineJoin="round"/>\n`
      : '') +
    (form.fill ? `${indent}  <path android:pathData="${form.fill}" android:fillColor="${ink}" android:fillType="evenOdd"/>\n` : '') +
    `${indent}</group>\n`
  );
}

/**
 * An app's static shortcuts' icons, `ic_shortcut_<key>` for each `{ key: glyph }`: from Android 8 an
 * adaptive icon (the tile behind, the glyph in the card's cream in front, the visible 72 of its 108
 * holding Material's 44 circle, so the glyph is 24/44 of it), and Android 7.1's own (the glyph on a 44
 * circle in a 48 square). Their tile is the mark's (matcha): static, as the widgets are.
 */
function shortcutIcons(write, glyphs) {
  write('values/ic_shortcuts.xml', `<resources>\n    <color name="ic_shortcut_background">${TILE}</color>\n</resources>\n`);
  // The 44 circle is the visible 72: the 24 glyph grows by as much.
  const scale = Math.round((72 / 44) * 10000) / 10000;
  const at = Math.round((54 - 12 * scale) * 100) / 100;
  for (const [key, glyph] of Object.entries(glyphs)) {
    write(`drawable/ic_shortcut_${key}_glyph.xml`, vector(108, 108, glyphPaths(glyph, scale, at, at, CARD_INK)));
    write(
      `drawable-anydpi-v26/ic_shortcut_${key}.xml`,
      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n' +
        '    <background android:drawable="@color/ic_shortcut_background" />\n' +
        `    <foreground android:drawable="@drawable/ic_shortcut_${key}_glyph" />\n` +
        `    <monochrome android:drawable="@drawable/ic_shortcut_${key}_glyph" />\n` +
        '</adaptive-icon>\n',
    );
    write(
      `drawable/ic_shortcut_${key}.xml`,
      vector(48, 48, `  <path android:pathData="M24 2A22 22 0 1 1 24 46A22 22 0 1 1 24 2Z" android:fillColor="${TILE}"/>\n${glyphPaths(glyph, 1, 12, 12, CARD_INK)}`),
    );
  }
}

// Carnet: its launcher, its reminders' status bar icon, its widgets' mark.
const write = writeIn(CARNET_RES);
launcher(write, card);
launcherPalettes(CARNET_RES, write, card);
// Status bar: white silhouette on transparent, the card fitted in 24dp with a 2dp margin.
{
  const scale = 20 / Math.max(BOUNDS.width, BOUNDS.height);
  const tx = 12 - (BOUNDS.x + BOUNDS.width / 2) * scale;
  const ty = 12 - (BOUNDS.y + BOUNDS.height / 2) * scale;
  write('drawable/ic_stat_carnet.xml', vector(24, 24, card(scale.toFixed(4), tx.toFixed(2), ty.toFixed(2), '  ', '#FFFFFFFF')));
}
// The widget's mark: the card on its pebble, as the app draws it.
write('drawable/ic_widget_mark.xml', vector(32, 100, `  <path android:pathData="${PEBBLE}" android:fillColor="${TILE}"/>\n${card(1, 0, 0, '  ')}`));
// Its static shortcuts (res/xml/shortcuts.xml), and its Quick Settings tile « Nouvelle note » (white: Android tints it).
shortcutIcons(write, { note: 'note', checklist: 'checklist', link: 'link', search: 'search' });
write('drawable/ic_tile_note.xml', vector(24, 24, glyphPaths('note', 1, 0, 0, '#FFFFFFFF')));

// Pages: its launcher.
const writePages = writeIn(PAGES_RES);
launcher(writePages, page);
launcherPalettes(PAGES_RES, writePages, page);
shortcutIcons(writePages, { page: 'pagePlus', search: 'search' });

// Contacts: its launcher, and its widgets' mark (the card and its person on the pebble).
