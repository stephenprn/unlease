/**
 * Generates the Android vector drawables (launcher, notification, the widgets' mark) from
 * packages/design/src/mark.ts and palette.ts (the widgets' own resources: tools/widgets/build_widget_resources.mjs). Run from the repository root.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const RES = resolve('mobile/notes/android/app/src/main/res');

const markSource = readFileSync('packages/design/src/mark.ts', 'utf8');
const markPath = name => new RegExp(`${name} =\\s*'([^']+)'`).exec(markSource)[1];
const markBox = name => Object.fromEntries([...new RegExp(`${name} = \\{([^}]*)\\}`).exec(markSource)[1].matchAll(/(\w+): (-?[\d.]+)/g)].map(([, key, value]) => [key, Number(value)]));
const PEBBLE = markPath('MARK_PEBBLE');
const CARD = markPath('MARK_CARD');
const BOUNDS = markBox('MARK_BOUNDS');

const paletteSource = readFileSync('packages/design/src/palette.ts', 'utf8');
const role = (mode, name) => {
  const block = new RegExp(`  ${mode}: \\{([\\s\\S]*?)\\n  \\}`).exec(paletteSource)[1];
  return new RegExp(`\\b${name}: '([^']+)'`).exec(block)[1];
};
const markBlock = /MARK_COLORS = \{([\s\S]*?)\}/.exec(paletteSource)[1];
const markColor = name => {
  const value = new RegExp(`${name}: ([^,\\n]+)`).exec(markBlock)[1].trim();
  const reference = /^ROLES\.(\w+)\.(\w+)$/.exec(value);
  return reference ? role(reference[1], reference[2]) : value.replace(/'/g, '');
};
const TILE = markColor('tile');
const CARD_INK = markColor('card');
const header = '<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/icons/build_android_drawables.mjs: do not edit. -->\n';
const write = (file, body) => {
  const path = resolve(RES, file);
  mkdirSync(resolve(path, '..'), { recursive: true });
  writeFileSync(path, header + body);
  console.log(file);
};

/** The card, its leaf cut out, on the mark's 100 grid, scaled by `scale` and moved by (tx, ty); `fill` for a one-colour silhouette. */
const card = (scale, tx, ty, indent, fill = CARD_INK) =>
  `${indent}<group android:translateX="${tx}" android:translateY="${ty}" android:scaleX="${scale}" android:scaleY="${scale}">\n` +
  `${indent}  <path android:pathData="${CARD}" android:fillColor="${fill}" android:fillType="evenOdd"/>\n` +
  `${indent}</group>\n`;
const vector = (dp, viewport, body) =>
  `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${dp}dp" android:height="${dp}dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">\n${body}</vector>\n`;

// Adaptive icon: 108dp canvas on the matcha ground (ic_launcher_background); the launcher shows the middle 72, the mark's 100 grid.
write('drawable/ic_launcher_foreground.xml', vector(108, 108, card(0.72, 18, 18, '  ')));
// Themed icon: one colour, the same placement; the leaf is a hole either way.
write('drawable/ic_launcher_monochrome.xml', vector(108, 108, card(0.72, 18, 18, '  ', '#FFFFFFFF')));
// Status bar: white silhouette on transparent, the card fitted in 24dp with a 2dp margin.
{
  const scale = 20 / Math.max(BOUNDS.width, BOUNDS.height);
  const tx = 12 - (BOUNDS.x + BOUNDS.width / 2) * scale;
  const ty = 12 - (BOUNDS.y + BOUNDS.height / 2) * scale;
  write('drawable/ic_stat_carnet.xml', vector(24, 24, card(scale.toFixed(4), tx.toFixed(2), ty.toFixed(2), '  ', '#FFFFFFFF')));
}
// The widget's mark: the card on its pebble, as the app draws it.
write('drawable/ic_widget_mark.xml', vector(32, 100, `  <path android:pathData="${PEBBLE}" android:fillColor="${TILE}"/>\n${card(1, 0, 0, '  ')}`));
// Android 7 has no adaptive icons: the card on a matcha pebble.
write('drawable/ic_launcher_legacy.xml', vector(48, 100, `  <path android:pathData="${PEBBLE}" android:fillColor="${TILE}"/>\n${card(1, 0, 0, '  ')}`));
