/**
 * Generate packages/design/src/glyphs.ts from Onde, Carnet's own icon set (tools/icons/onde.mjs): for
 * every icon its line form, and for the few a control can show selected (a drawer destination, a
 * toggle that is on) its solid form. Run from the repository root:
 *
 *   node tools/icons/build_glyphs.mjs
 *
 * Then regenerate the Android widget icons: node tools/icons/build_android_drawables.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { GLYPH_STROKE, ICONS, SOLID } from './onde.mjs';

const formLiteral = form => `{ stroke: ${form.stroke ? JSON.stringify(form.stroke) : 'null'}, fill: ${form.fill ? JSON.stringify(form.fill) : 'null'} }`;

const out = [];
for (const [name, glyph] of Object.entries(ICONS)) {
  if (!glyph.line.stroke && !glyph.line.fill) throw new Error(`${name} draws nothing`);
  if (SOLID.includes(name) !== Boolean(glyph.solid)) throw new Error(`${name}: solid form ${glyph.solid ? 'not listed' : 'missing'}`);
  out.push(`  ${name}: { line: ${formLiteral(glyph.line)}, solid: ${glyph.solid ? formLiteral(glyph.solid) : 'null'} },`);
}

const header = `/**
 * Icon glyphs for the phone and the web: Onde, Carnet's own set, on a 24-unit grid. A form is an
 * even line (\`stroke\`, drawn GLYPH_STROKE wide with round ends and joins) and its small filled
 * parts (\`fill\`, even-odd); a glyph a control can show selected also has a solid form. Every
 * straight line takes one soft wave, frames swell a little, large circles breathe. GENERATED by
 * tools/icons/build_glyphs.mjs from tools/icons/onde.mjs: do not edit.
 */

export interface GlyphForm {
  /** The line, stroked GLYPH_STROKE wide with round caps and joins; null where the form has none. */
  readonly stroke: string | null;
  /** The filled parts (dots, a solid shape with its cut-outs), even-odd; null where the form has none. */
  readonly fill: string | null;
}

export interface Glyph {
  readonly line: GlyphForm;
  /** The glyph filled, for a selected control; null where no control shows it selected. */
  readonly solid: GlyphForm | null;
}

export const GLYPH_GRID = 24;

/** The one line width every glyph is drawn with, in grid units. */
export const GLYPH_STROKE = ${GLYPH_STROKE};

export const GLYPHS = {
`;
writeFileSync(
  resolve('packages/design/src/glyphs.ts'),
  `${header}${out.join('\n')}\n} as const satisfies Record<string, Glyph>;\n\nexport type GlyphName = keyof typeof GLYPHS;\n`,
);
console.log(`wrote ${out.length} glyphs`);
