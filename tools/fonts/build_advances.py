"""
Writes packages/design/src/advances.ts: Signika's advance width for every character the app's fonts
carry, in thousandths of an em, for the two weights card text is set in (Regular, Bold). The
board computes card heights from them instead of measuring. Kerning moves a line by under 0.5%,
so it is left out. Run from the repository root after build_fonts.py; needs fontTools.

    python3 tools/fonts/build_advances.py
"""
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "mobile/notes/assets/fonts"
OUT = ROOT / "packages/design/src/advances.ts"
WEIGHTS = {"regular": "Signika-Regular.ttf", "bold": "Signika-Bold.ttf"}


def runs(font: TTFont) -> list[tuple[int, list[int]]]:
    """Contiguous code points with their advances, so the table stays small."""
    upm = font["head"].unitsPerEm
    hmtx = font["hmtx"]
    widths = {code: round(hmtx[glyph][0] * 1000 / upm) for code, glyph in font.getBestCmap().items() if code >= 0x20}
    out: list[tuple[int, list[int]]] = []
    for code in sorted(widths):
        if out and out[-1][0] + len(out[-1][1]) == code:
            out[-1][1].append(widths[code])
        else:
            out.append((code, [widths[code]]))
    return out


def main() -> None:
    lines = [
        "/**",
        " * Signika's advance widths in thousandths of an em, per code point, as runs of",
        " * [first code point, widths…]. GENERATED by tools/fonts/build_advances.py: do not edit.",
        " */",
        "",
        "export type AdvanceWeight = 'regular' | 'bold';",
        "",
        "export const ADVANCES: Record<AdvanceWeight, readonly (readonly [number, readonly number[]])[]> = {",
    ]
    for weight, file in WEIGHTS.items():
        lines.append(f"  {weight}: [")
        for start, widths in runs(TTFont(FONTS / file)):
            lines.append(f"    [{start}, [{', '.join(map(str, widths))}]],")
        lines.append("  ],")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
