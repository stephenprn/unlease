function english(text: string): string {
  const found = DEMO_ENGLISH.get(demoTextKey(text));
  if (found === undefined) return text;
  const dates = text.match(DATE) ?? [];
  let at = 0;
  return found.replace(/\{@date\}/g, () => dates[at++] ?? '{@date}');
}

function translated(value: unknown): unknown {
  if (typeof value === 'string') return english(value);
  if (Array.isArray(value)) return value.map(translated);
  if (value !== null && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, inner]) => [key, translated(inner)]));
  return value;
}

/**
 * The demo's records in English: every string field through the dictionary, a link's address when it
 * is one of `DEMO_ENGLISH_URLS`, its reading's language `en`, and what a link was read with following
 * its template's English fields (a template's signature is made of its fields' words).
 */
export function inEnglish(records: readonly SyncRecord[]): SyncRecord[] {
  const signatures = new Map<string, string>();
  for (const record of records) {
    if (record.type !== 'linkTemplate' || !Array.isArray(record.fields.fields)) continue;
    const fields = record.fields.fields as TemplateField[];
    signatures.set(templateSignature(fields), templateSignature(translated(fields) as TemplateField[]));
  }
  return records.map(record => {
    const fields = translated(record.fields) as Record<string, unknown>;
    if (record.type === 'link') {
      const url = typeof record.fields.url === 'string' ? record.fields.url : '';
      fields.url = DEMO_ENGLISH_URLS.get(url) ?? url;
      fields.lang = 'en';
      const readWith = record.fields.readWith;
      if (typeof readWith === 'string') fields.readWith = signatures.get(readWith) ?? readWith;
    }
    return { ...record, fields };
  });
}
